print("--- Assembling supplementary tables ---")
OUT.parent.mkdir(parents=True, exist_ok=True)
readme, missing = [], []
with pd.ExcelWriter(OUT) as w:
    hp = pd.DataFrame(HYPERPARAMS, columns=["order", "sub-model", "architecture / hyperparameters", "training", "relevance"])
    write_blocks(w, "S1_hyperparameters", "Hyperparameters of the BRS sub-models", [("", hp)])
    readme.append(("S1_hyperparameters", "Hyperparameters of the BRS sub-models", "ok"))
    for sheet, title, sources in TABLES:
        blocks = []
        for path, sh, flt in sources:
            df = load(path, sh, flt)
            if df is None:
                missing.append(f"{sheet}: {path}")
                continue
            if sheet != ASSAY_SHEET:
                df = df[[c for c in df.columns if not ASSAY_COLS.search(str(c))]]
            label = BLOCK_LABELS.get((path.name, sh))
            blocks.append(((label + f"  (source: {path.name} [{sh}])") if label else
                           f"Source: {path.name}" + (f" [{sh}]" if isinstance(sh, str) else ""), df))
        status = "ok" if len(blocks) == len(sources) else ("PENDING" if not blocks else "partial")
        if blocks:
            write_blocks(w, sheet, title, blocks)
        readme.append((sheet, title, status))
    pd.DataFrame(readme, columns=["sheet", "content", "status"]).to_excel(w, sheet_name="README", index=False)

# S16A/S16B are read by experimenters: column widths per part, wrapped text, bold titles, merged read-me text
import math  # noqa: E402

from openpyxl import load_workbook  # noqa: E402
from openpyxl.styles import Alignment, Font  # noqa: E402

WIDTHS = {   # one width per column of the part shown on the sheet
    "S16A_single_candidates": [30, 10, 30, 28, 18, 11, 22, 11, 10, 9, 26, 9, 13, 18, 46, 46, 46],
    "S16B_combinations": [30, 44, 7, 15, 13, 11, 13, 12, 16, 24, 28, 12, 18, 46, 46, 46],
}
TOP = Alignment(wrap_text=True, vertical="top")
wb = load_workbook(OUT)
for name, widths in WIDTHS.items():
    ws = wb[name]
    letters = [ws.cell(row=1, column=i + 1).column_letter for i in range(len(widths))]
    for col, width in zip(letters, widths):
        ws.column_dimensions[col].width = width
    total = sum(widths[1:])
    in_readme = False
    for row in ws.iter_rows():
        r, first = row[0].row, row[0].value
        for cell in row:
            if cell.value is not None:
                cell.alignment = TOP
        if r == 1:                                   # title across the sheet
            ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(widths))
            ws.row_dimensions[1].height = 15 * math.ceil(len(str(first)) / (1.1 * sum(widths)) + 0.5)
            row[0].font = Font(bold=True)
            continue
        if isinstance(first, str) and first.startswith(("Part ", "Read me")):
            row[0].font = Font(bold=True)
            row[0].alignment = Alignment(wrap_text=False, vertical="top")
            in_readme = first.startswith("Read me")
            continue
        if in_readme and first is None:
            in_readme = False
        if in_readme and first not in ("field",) and row[1].value is not None:   # read-me text across the sheet
            ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=len(widths))
            ws.row_dimensions[r].height = 15 * math.ceil(len(str(row[1].value)) / (1.1 * total))
        elif first in ("target strain", "field"):    # column headers
            for cell in row:
                if cell.value is not None:
                    cell.font = Font(bold=True)
    if name == "S16B_combinations":          # title, label and header above row 5; strain and combination on the left
        ws.freeze_panes = "C5"
wb.save(OUT)

