# ==========================================
# 2) Helpers
# ==========================================
def load(path: Path, sheet, row_filter):
    if not path.exists():
        return None
    df = pd.read_csv(path) if path.suffix == ".csv" else pd.read_excel(path, sheet_name=sheet)
    if "dataset" in df.columns:     # label hard-coded as p=1119 in the earlier benchmark run; the data have 1,092 metabolites
        df["dataset"] = df["dataset"].astype(str).str.replace("KOMP Pmm2 (n=46, p=1119)", "KOMP Pmm2 (n=46, p=1092)",
                                                              regex=False)
    if row_filter is not None:
        col, key = row_filter
        df = df[df[col].astype(str).str.contains(key, regex=False)]
    return df


def write_blocks(writer, sheet, title, blocks):
    """Stack several source tables vertically on one sheet, each under its own label."""
    row = 0
    pd.DataFrame([[f"Table {sheet.split('_')[0]}. {title}"]]).to_excel(writer, sheet_name=sheet, index=False,
                                                                         header=False, startrow=row)
    row += 2
    for label, df in blocks:
        pd.DataFrame([[label]]).to_excel(writer, sheet_name=sheet, index=False, header=False, startrow=row)
        df.to_excel(writer, sheet_name=sheet, index=False, startrow=row + 1)
        row += len(df) + 4


