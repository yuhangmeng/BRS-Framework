# -*- coding: utf-8 -*-
"""
Table 3: candidate mixtures for strain-specific assays. For each strain, metabolites are listed in the order in which
they enter the mixture (decreasing full-data selection probability for that strain) up to the size of the final
mixture, chosen on all accessions with the size rule that the strict nested cross-validation applies inside each
training set (strict_nested_cv.py). AUC: strict nested-CV AUC for that fixed size (descriptive).
Members below the selection threshold (pi < 0.4) belong to the exploratory extension and are marked.

Input : supplementary/ST_incremental_signature.xlsx (wetlab_lists: order, pi, leverage),
        supplementary/ST_strict_nested_cv.xlsx (final_mixtures, curves, mixtures)
Output: 论文/overleaf_v6/tables/table3_mixtures.tex, table3_mixtures.json (cells for the Word copy)
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "supplementary" / "ST_incremental_signature.xlsx"
STRICT = ROOT / "supplementary" / "ST_strict_nested_cv.xlsx"
OUT_TEX = ROOT / "论文" / "overleaf_v6" / "tables" / "table3_mixtures.tex"
STRAINS = [("NF", "AOA"), ("NV", "AOA"), ("NM", "AOB"), ("NU", "AOB")]
LEV_FLAG, PI_THR = 0.7, 0.4

wet = pd.read_excel(SRC, sheet_name="wetlab_lists")
final = pd.read_excel(STRICT, sheet_name="final_mixtures").set_index("target")
curve = pd.read_excel(STRICT, sheet_name="curves").set_index(["target", "k"])["nested-CV AUC (fixed k)"]
K_COL = "k for the final mixture (inner rule on 25 full-data pairs)"


def tex(s):
    s = str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")
    s = s.replace("6,8C-glycosylated", "6,8-C-Glycosylated").replace("gamma-", r"$\gamma$-")
    s = s.replace("Fatty acid - C18H30O3", r"Fatty acid (C$_{18}$H$_{30}$O$_3$)")
    s = s.replace("N-acetyltryptophan", "N-Acetyltryptophan")
    s = s.replace("α", r"$\alpha$").replace("β", r"$\beta$").replace("′", r"$'$")     # pdflatex: no raw Greek/prime
    return s.replace("Hydroxybenzenepropanoic", r"Hydroxy\-benzene\-propanoic")


CAPTION = (
    "Candidate mixtures for strain-specific assays. For each strain, metabolites enter the mixture in order of "
    "decreasing selection probability {pi} for that strain, up to the size of the final mixture, chosen on all "
    "accessions with the rule that the nested cross-validation applies inside each training set (Section 2.1.3). "
    "Lev.: single-accession leverage ({dag}, {geq} 0.7). {ddag}, below the selection threshold ({pi} < 0.4; exploratory "
    "pool): all NF members pass the threshold, the NV and NM mixtures contain an exploratory extension, and the NU "
    "mixture consists only of exploratory members, all of which were in the exploratory pool of the combination test "
    "(Section 2.1.4). AUC: nested cross-validation AUC of the mixture up to and including "
    "that metabolite for the strain's own high-inhibition label, at this fixed size (descriptive); the AUC of the "
    "procedure that chooses the size within the training folds is given in the text and in Supplementary Table S19.")
lines = [
    r"% Generated by Table3_mixtures.py -- do not edit by hand",
    r"\begin{table}[!htbp]",
    r"\caption{" + CAPTION.format(pi=r"$\pi$", dag=r"$^\dagger$", geq=r"$\geq$", ddag=r"$^\ddagger$")
    .replace("(Section 2.1.3)", r"(Section~\ref{sec:mix})").replace("(Section 2.1.4)", r"(Section~\ref{sec:gated})")
    + r"}\label{tab:mixtures}",
    r"\footnotesize\setlength{\tabcolsep}{3pt}",
    r"\begin{tabular*}{\columnwidth}{@{\extracolsep\fill}cl>{\raggedright\arraybackslash}p{6.4cm}ccc@{\extracolsep\fill}}",
    r"\toprule",
    r"Strain & Step & Metabolite & $\pi$ & Lev. & AUC \\",
    r"\midrule",
]
word_rows = []
for i, (s, guild) in enumerate(STRAINS):
    k_rec = int(final.loc[s, K_COL])
    d = wet[(wet.strain == s) & (wet.step <= k_rec)].sort_values("step")
    for j, (_, r) in enumerate(d.iterrows()):
        lev = r["leverage"]
        lev_txt = "--" if pd.isna(lev) else ("%.2f" % lev) + (r"$^\dagger$" if lev >= LEV_FLAG else "")
        first = f"{s} ({guild})" if j == 0 else ""      # plain cell: survives the pandoc conversion to Word
        below = r["pi_strain"] < PI_THR
        auc_k = curve.loc[(s, int(r["step"]))]
        lines.append(" & ".join([first, str(int(r["step"])), tex(r["metabolite_added"]) + (r"$^\ddagger$" if below else ""),
                                 "%.2f" % r["pi_strain"], lev_txt, "%.2f" % auc_k]) + r" \\")
        name = (str(r["metabolite_added"]).replace("6,8C-glycosylated", "6,8-C-Glycosylated")
                .replace("gamma-", "γ-").replace("Fatty acid - C18H30O3", "Fatty acid (C₁₈H₃₀O₃)")
                .replace("N-acetyltryptophan", "N-Acetyltryptophan"))
        word_rows.append([first, str(int(r["step"])), name + ("‡" if below else ""), "%.2f" % r["pi_strain"],
                          ("--" if pd.isna(lev) else "%.2f" % lev + ("†" if lev >= LEV_FLAG else "")), "%.2f" % auc_k])
    if i < len(STRAINS) - 1:
        lines.append(r"\midrule")
lines += [r"\botrule", r"\end{tabular*}", r"\end{table}", ""]
OUT_TEX.write_text("\n".join(lines), encoding="utf-8")
OUT_TEX.with_suffix(".json").write_text(json.dumps({
    "caption": CAPTION.format(pi="π", dag="†", geq="≥", ddag="‡"),
    "head": ["Strain", "Step", "Metabolite", "π", "Lev.", "AUC"], "rows": word_rows}, ensure_ascii=False, indent=1),
    encoding="utf-8")
print("\n".join(lines))
